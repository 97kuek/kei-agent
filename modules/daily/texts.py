"""Daily と振り返りの指示（AI に渡す依頼）と、答えの形。本体の窓口には触れない。"""

from __future__ import annotations

# 材料は、ファイルにせずプロンプトのこの間に入れる
MATERIAL_START = "--- 材料ここから ---"
MATERIAL_END = "--- 材料ここまで ---"
# 振り返りのスレッドに並べる締切（明日・明後日まで）
REVIEW_DUE_DAYS = 2
# 振り返るときの問い（Codex のアプリなどで振り返る材料）。Slack には出さず、日別記録のレトプラにだけ残す
REVIEW_QUESTIONS = ("### 振り返りの問い\n"
                    "1. 今日分かったことは何か（〜について、など具体的に）\n"
                    "2. 明日やることは何か")
# 答えの見出し（この順で1回ずつ。core.checked_sections で確かめる）
DAILY_HEADINGS = (
    "**今日のタスク**",
    "**夜間処理の結果**",
    "**確認待ち・期日・止まっているテーマ・返事待ち**",
    "**今日考えるとよい問い**",
)
REVIEW_HEADINGS = ("**今日の成果**", "**未完了タスク**")
# 振り返りの最後の1行（決まった文なので、無ければ足す）
NIGHT_QUESTION = "夜間に実行したいタスクはありますか？"


def material(text: str, limit: int) -> str:
    """プロンプトに入れる材料の部分。"""
    return (f"{MATERIAL_START}\n{text.strip()}\n{MATERIAL_END}\n"
            f"（材料は {limit} 字までで、超えた分は後ろの振り返りから省いています）")


def daily_prompt(day: str, material_text: str) -> str:
    return (
        f"[Kei Agent の定期処理: Daily {day}]\n"
        "次は前回の Daily からの材料です。\n\n"
        f"{material_text}\n\n"
        "材料（Notion のテーマの Task を含む）と、そこに書かれたスレッドのログを読み、"
        "今日の議論の起点になる Daily を書いてください。\n\n"
        "**次の4つを、この順と見出しで書いてください。**ほかの見出しは足さないでください。\n"
        "スマホでも読めるように、全体を1画面に収めます。\n\n"
        "**今日のタスク**\n"
        "材料の「今日が期日の Task」を1行ずつ。**済みのものは `~取り消し線~` にする**"
        "（やったことも見えるように）。1件も無ければ「なし」の1行。\n\n"
        "**夜間処理の結果**\n"
        "夜間に終わったジョブと Task。無ければ1行で。\n\n"
        "**確認待ち・期日・止まっているテーマ・返事待ち**\n"
        "確認待ちの Task、期日が近い Task、止まっているテーマ、返事待ちのスレッド、"
        "今週の時間の気になる点。**何も無いものはまとめて1行にする**（「いずれもなし」）。\n\n"
        "**今日考えるとよい問い**\n"
        "2〜3個。番号を振る。前日のスレッドの結果と、前日の振り返りを踏まえる。\n\n"
        "**前日の動きの説明と、先行研究の新着は書かないでください。**前者は長くなって読み飛ばすため、"
        "後者はテーマのチャンネルに別で流れているためです（朝の予定に「どのテーマに新着があったか」だけ出ます）。\n\n"
        "返答は Kei Agent がそのまま共通 Notion ホームの日別記録に保存します。ファイルは作らないでください。\n"
        "Slack に出す本文は、次の marker の間にだけ書いてください。"
        "marker の外には何も書かず、作業手順・tool 名・ファイル名は本文に入れません。\n"
        "<<kei-agent-final>>\n（ここに4 section）\n<<kei-agent-final-end>>"
    )


def review_prompt(day: str, material_text: str) -> str:
    return (
        f"[Kei Agent の定期処理: Retro & Planning {day}]\n"
        "次は今日の材料です。\n\n"
        f"{material_text}\n\n"
        "材料と、そこに書かれたスレッドのログを読み、今日を振り返ってください。\n\n"
        "**Slack への返答は、次の2つの見出しと最後の1行だけ**にしてください。"
        "ほかの見出しや説明を足さないでください。\n\n"
        "**今日の成果**\n"
        "材料の「今日が期日の Task」のうち**済みのもの**を1行ずつ。"
        "Task になっていないが今日片付いたことがあれば、それも1行で足してよい。無ければ「なし」。\n\n"
        "**未完了タスク**\n"
        "同じ Task のうち**終わっていないもの**を1行ずつ。無ければ「なし」。\n\n"
        "最後に、次の1行をそのまま書いてください。\n"
        f"{NIGHT_QUESTION}\n\n"
        "返答は Kei Agent がそのまま共通 Notion ホームの日別記録（レトプラ）に保存します。ファイルは作らないでください。"
        "このあと、このスレッドに振り返りの結論が貼られたら、Kei Agent が同じ日別記録に追記します。"
        "ファイルには書かず、受け取ったことだけを短く返してください。\n\n"
        "Slack に出す本文は次の marker の間にだけ書いてください。marker の外には何も書かず、"
        "作業手順・tool 名・ファイル名・provider 名は本文に入れません。\n"
        "<<kei-agent-final>>\n（ここに指定の3 block）\n<<kei-agent-final-end>>"
    )


# 振り返りのあと、スレッドで聞くこと（返事が来たら、会話で学びに整理する）
RETRO_QUESTION = ("今日、職場や学校で学んだこと・印象に残った助言はある？ ひと言でいいよ。"
                  "少し聞き返して整理したら、Knowledge に残すね。")
# 整理できたときの合図の行（そのあとに JSON。Slack には出さない）
LEARNING_MARKER = "📒 学び"


def talk_prompt(day: str, history: str, saved: list[str], latest: str = "") -> str:
    """振り返りのスレッドの会話。学んだこと・助言を聞き返して言語化し、まとまったら学びに整理する。"""
    again = ("前に残した学び: " + "、".join(saved) + "。直してと言われたら、直した全体をもう一度出す（前のものは差し替える）。\n\n"
             if saved else "")
    return (
        f"[Kei Agent の振り返り {day}: 学びの会話]\n"
        "あなたは依頼者の振り返りの相手。職場や学校で学んだこと、大切な助言を、そのまま流さずに言語化して残すのを手伝う。\n\n"
        f"{history}\n\n" + (f"依頼者のいちばん新しい返事:\n{latest}\n\n" if latest else "") + f"{again}"
        "進め方:\n"
        "- 話がまだ曖昧なら、1回に1つだけ短く聞き返す（どんな場面だったか、なぜ大事だと思ったか、次にどう使うか）。"
        "聞き返すのは合わせて2回まで\n"
        "- 場面・学んだこと・次にどう使うかが分かったら、確かめずに学びに整理する（1〜3件。話に無いことは足さない）\n"
        "- 特に無い・今日はいい、と言われたら、ひと言返して終える（学びは作らない）\n\n"
        "Slack に出す本文は <<kei-agent-final>> と <<kei-agent-final-end>> の間にだけ書く。日本語で短く。"
        "見出し・表・作業手順は書かない。\n"
        f"学びに整理したときは、本文の最後に `{LEARNING_MARKER}` の1行と、次の形の JSON を1行で書く（marker の内側）:\n"
        '[{"title": "学びを1行で", "kind": "学び|助言|気づき", '
        '"source": "誰から・どの場面で", "scene": "場面", "lesson": "学んだこと", "next": "次にどう使うか"}]\n'
        "本文には、残す学びの題を1行ずつ書く（JSON の中身は繰り返さない）。"
    )
